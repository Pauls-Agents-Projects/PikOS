#!/usr/bin/env python3
"""Generate the deterministic gzip-compressed PikOS settings-page header."""

from __future__ import annotations

import gzip
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "include" / "WebUi.h"
OUTPUT = ROOT / "include" / "WebUiGzip.h"


def main() -> None:
    source = SOURCE.read_text(encoding="utf-8")
    match = re.search(r'R"HTML\(\n?(.*)\)HTML";', source, re.DOTALL)
    if match is None:
        raise SystemExit("WebUi.h raw HTML block was not found")

    payload = gzip.compress(match.group(1).encode("utf-8"), compresslevel=9,
                            mtime=0)
    rows = []
    for offset in range(0, len(payload), 16):
        rows.append("    " + ", ".join(
            f"0x{byte:02x}" for byte in payload[offset:offset + 16]
        ) + ",")
    generated = "\n".join([
        "// Generated by scripts/generate_web_ui_gzip.py; do not edit.",
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        "namespace pixelos {",
        "",
        "static const uint8_t kWebUiGzip[] PROGMEM = {",
        *rows,
        "};",
        "static constexpr size_t kWebUiGzipSize = sizeof(kWebUiGzip);",
        "",
        "}  // namespace pixelos",
        "",
    ])
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"{len(match.group(1).encode('utf-8'))} -> {len(payload)} bytes")


if __name__ == "__main__":
    main()
