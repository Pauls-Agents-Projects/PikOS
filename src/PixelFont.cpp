uint32_t nextCodepoint(const String& text, size_t& offset) {
  if (offset >= text.length()) {
    return 0;
  }
  const uint8_t first = static_cast<uint8_t>(text[offset++]);
  if ((first & 0x80) == 0) {
    return first;
  }
  if ((first & 0xe0) == 0xc0 && offset < text.length()) {
    const uint8_t second = static_cast<uint8_t>(text[offset++]);
    return ((first & 0x1f) << 6) | (second & 0x3f);
  }
  if ((first & 0xf0) == 0xe0 && offset + 1 < text.length()) {
    const uint8_t second = static_cast<uint8_t>(text[offset++]);
    const uint8_t third = static_cast<uint8_t>(text[offset++]);
    return ((first & 0x0f) << 12) | ((second & 0x3f) << 6) |
           (third & 0x3f);
  }
  if ((first & 0xf8) == 0xf0 && offset + 2 < text.length()) {
    const uint8_t second = static_cast<uint8_t>(text[offset++]);
    const uint8_t third = static_cast<uint8_t>(text[offset++]);
    const uint8_t fourth = static_cast<uint8_t>(text[offset++]);
    return ((first & 0x07) << 18) | ((second & 0x3f) << 12) |
           ((third & 0x3f) << 6) | (fourth & 0x3f);
  }
  return '?';
}

