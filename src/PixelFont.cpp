Glyph clockGlyphFor(uint32_t codepoint) {
  // The regular font's five-column numerals are useful in scrolling text but
  // make a five-character time wider than the clock's icon-and-text area.
  // These three-column, seven-row figures keep every HH:MM value on one line.
  switch (codepoint) {
    case '0':
      return makeGlyph(3, 0x07, 0x05, 0x05, 0x05, 0x05, 0x05, 0x07);
    case '1':
      return makeGlyph(3, 0x02, 0x06, 0x02, 0x02, 0x02, 0x02, 0x07);
    case '2':
      return makeGlyph(3, 0x07, 0x01, 0x01, 0x07, 0x04, 0x04, 0x07);
    case '3':
      return makeGlyph(3, 0x07, 0x01, 0x01, 0x07, 0x01, 0x01, 0x07);
    case '4':
      return makeGlyph(3, 0x05, 0x05, 0x05, 0x07, 0x01, 0x01, 0x01);
    case '5':
      return makeGlyph(3, 0x07, 0x04, 0x04, 0x07, 0x01, 0x01, 0x07);
    case '6':
      return makeGlyph(3, 0x07, 0x04, 0x04, 0x07, 0x05, 0x05, 0x07);
    case '7':
      return makeGlyph(3, 0x07, 0x01, 0x01, 0x02, 0x02, 0x02, 0x02);
    case '8':
      return makeGlyph(3, 0x07, 0x05, 0x05, 0x07, 0x05, 0x05, 0x07);
    case '9':
      return makeGlyph(3, 0x07, 0x05, 0x05, 0x07, 0x01, 0x01, 0x07);
    case ':':
      return makeGlyph(1, 0x00, 0x01, 0x01, 0x00, 0x01, 0x01, 0x00);
    case ' ':
      return makeGlyph(1, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00);
    default:
      return glyphFor(codepoint);
  }
}

int16_t measureText(const String& text) {
  size_t offset = 0;
  int16_t width = 0;
  while (offset < text.length()) {
    const Glyph glyph = glyphFor(nextCodepoint(text, offset));
    width += glyph.width + 1;
  }
  return width > 0 ? width - 1 : 0;
}

int16_t measureClockText(const String& text) {
  size_t offset = 0;
  int16_t width = 0;
  while (offset < text.length()) {
    const Glyph glyph = clockGlyphFor(nextCodepoint(text, offset));
    width += glyph.width + 1;
  }
  return width > 0 ? width - 1 : 0;
}

String uppercaseForDisplay(const String& text) {
  String output;
  output.reserve(text.length());
  size_t offset = 0;
  while (offset < text.length()) {
    appendCodepoint(output, displayUpper(nextCodepoint(text, offset)));
  }
  return output;
}

