Glyph makeGlyph(uint8_t width, uint8_t r0, uint8_t r1, uint8_t r2,
                uint8_t r3, uint8_t r4, uint8_t r5, uint8_t r6) {
  Glyph result{width, {r0, r1, r2, r3, r4, r5, r6}};
  return result;
}

void appendCodepoint(String& output, uint32_t codepoint) {
  if (codepoint < 0x80) {
    output += static_cast<char>(codepoint);
  } else if (codepoint < 0x800) {
    output += static_cast<char>(0xc0 | (codepoint >> 6));
    output += static_cast<char>(0x80 | (codepoint & 0x3f));
  } else {
    output += static_cast<char>(0xe0 | (codepoint >> 12));
    output += static_cast<char>(0x80 | ((codepoint >> 6) & 0x3f));
    output += static_cast<char>(0x80 | (codepoint & 0x3f));
  }
}

uint32_t displayUpper(uint32_t codepoint) {
  switch (codepoint) {
    case 0x2013:
    case 0x2014:
      return '-';
    case 0x2018:
    case 0x2019:
      return '\'';
    case 0x201c:
    case 0x201d:
      return '"';
    case 0x2026:
      return '.';
    case 0x00a0:
      return ' ';
    default:
      return codepoint;
  }
}

